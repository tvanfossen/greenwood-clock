## @file gen_kconfig.py
## @brief Host tool: write the host LVGL configuration header from the device sdkconfig.h (platform-only options overridden, "A:" rooted at the repo sdcard/).
## @version 1
"""Generate the host LVGL configuration from the device's own sdkconfig.h.

The host build of the LVGL fork must draw what the device draws, so it takes every
CONFIG_LV_* value from the firmware build (colour depth, fonts, widgets, theme options) and
overrides only what cannot exist on a PC: the ESP32-P4 PPA, the ThorVG/Lottie C++ backend
and the device allocator.

LVGL's "A:" drive (the device SD card) is pointed at the given host folder, so host code
opens the same "A:/..." paths the firmware does.

Usage: gen_kconfig.py <build/config/sdkconfig.h> <out.h> <host sdcard dir>
"""

import re
import sys
from pathlib import Path

## Platform-only options replaced on the host: name -> value (None removes it).
OVERRIDES = {
    "CONFIG_LV_USE_PPA": None,
    "CONFIG_LV_USE_PPA_IMG": None,
    "CONFIG_LV_USE_LOTTIE": None,
    "CONFIG_LV_USE_THORVG": None,
    "CONFIG_LV_USE_THORVG_INTERNAL": None,
    "CONFIG_LV_USE_VECTOR_GRAPHIC": None,
    "CONFIG_LV_USE_CUSTOM_MALLOC": None,
    "CONFIG_LV_USE_CLIB_MALLOC": "1",
    "CONFIG_LV_USE_LOG": None,
}


## @brief Keep the CONFIG_LV_* defines of @p text with the host overrides applied, and the
## "A:" drive rooted at @p sdcard.
## @utility
## @version 1
## @return The header text.
def host_config(text, sdcard):
    lines = [
        "/* Generated by tools/lvgl_host/gen_kconfig.py from the device sdkconfig.h. */",
        "#pragma once",
    ]
    seen = set()
    for m in re.finditer(r"^#define (CONFIG_LV\w*) (.*)$", text, re.M):
        name, value = m.group(1), m.group(2)
        seen.add(name)
        if name in OVERRIDES:
            value = OVERRIDES[name]
        if name == "CONFIG_LV_FS_POSIX_PATH":
            value = f'"{sdcard}"'
        if value is not None:
            lines.append(f"#define {name} {value}")
    lines += [
        f"#define {n} {v}"
        for n, v in OVERRIDES.items()
        if v is not None and n not in seen
    ]
    return "\n".join(lines) + "\n"


## @brief Entry point: read the sdkconfig header, write the host one.
## @utility
## @version 1
def main():
    src, out, sdcard = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]).resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    text = host_config(src.read_text(), sdcard.as_posix())
    if (
        not out.exists() or out.read_text() != text
    ):  # keep mtime: no needless LVGL rebuild
        out.write_text(text)


if __name__ == "__main__":
    main()
