/**
 * @file gen_moon_albedo.c
 * @version 1
 * @brief Host tool: write the moon's surface texture (sky_moon_albedo.c) from
 *        sky_moon_albedo_model: SKY_MOON_TEX x SKY_MOON_TEX brightness samples, so the clock
 *        samples a table instead of computing the surface per pixel. Run by `inv moon-texture`.
 */
#include "sky_paint.h"

#include <stdio.h>

/** A placeholder so the model file links here; the real table is what this writes. */
const uint8_t SKY_MOON_ALBEDO[SKY_MOON_TEX * SKY_MOON_TEX];

/**
 * @brief Write the texture as C to the file named by argv[1].
 * @version 1
 * @utility
 * @return 0, or 1 when the file cannot be written.
 */
int main(int argc, char **argv)
{
    FILE *f = argc > 1 ? fopen(argv[1], "w") : NULL;
    if (!f) return 1;
    fprintf(f, "/**\n * @file sky_moon_albedo.c\n * @version 1\n"
               " * @brief The moon's surface texture (see sky_paint.h), generated by\n"
               " *        tools/sky_texture/gen_moon_albedo.c (`inv moon-texture`): do not edit.\n"
               " */\n#include \"sky_paint.h\"\n\n"
               "const uint8_t SKY_MOON_ALBEDO[SKY_MOON_TEX * SKY_MOON_TEX] = {\n");
    for (int py = 0; py < SKY_MOON_TEX; py++) {
        fprintf(f, "   ");
        for (int px = 0; px < SKY_MOON_TEX; px++) {
            float x = -1.0f + 2.0f * px / (SKY_MOON_TEX - 1), y = 1.0f - 2.0f * py / (SKY_MOON_TEX - 1);
            float a = sky_moon_albedo_model(x, y) / SKY_MOON_ALBEDO_MAX * 255.0f + 0.5f;
            fprintf(f, " %d,", a < 0 ? 0 : (a > 255 ? 255 : (int)a));
        }
        fprintf(f, "\n");
    }
    fprintf(f, "};\n");
    return fclose(f) ? 1 : 0;
}
